#!/usr/bin/env python3
"""Symbolic checks for P3_CAUSAL_PRIMITIVE_STORAGE_IDENTITY.md."""

import sympy as sp


# Gamma cell: F=z'+2 alpha z and y=z'/alpha.
alpha = sp.symbols("alpha", positive=True, real=True)
zp, z = sp.symbols("zp z", real=True)
f = zp + 2 * alpha * z
y = zp / alpha
gamma_supply = sp.expand(f * y)
gamma_balance_density = zp**2 / alpha + 2 * z * zp
assert sp.simplify(gamma_supply - gamma_balance_density) == 0

# Prime cell: F=x-r x_delay and y=x+r x_delay.
r, x, xd = sp.symbols("r x xd", real=True)
assert sp.expand((x - r * xd) * (x + r * xd)) == x**2 - r**2 * xd**2

# Primitive polynomial division.
D, lam = sp.symbols("D lam")
L0 = -D**2 + sp.Rational(1, 4)
division = (-D + lam) * (D + lam) - (lam**2 - sp.Rational(1, 4))
assert sp.expand(L0 - division) == 0

# Quarter cancellation at n=0.
assert (sp.Rational(1, 2) ** 2 - sp.Rational(1, 4)) == 0

# Closed generating function for the terminal Gamma Hankel kernel.
q = sp.symbols("q")
s2 = q * (1 + q) / (1 - q) ** 3
s3 = q * (1 + 4 * q + q**2) / (1 - q) ** 4
s4 = q * (1 + 11 * q + 11 * q**2 + q**3) / (1 - q) ** 5
closed = 4 * q * (q**3 + 31 * q**2 + 55 * q + 9) / (1 - q) ** 5
assert sp.simplify(16 * s4 + 16 * s3 + 4 * s2 - closed) == 0

print("PASS: Gamma causal balance")
print("PASS: prime-delay causal balance")
print("PASS: primitive polynomial division")
print("PASS: quarter n=0 terminal cancellation")
print("PASS: closed terminal Gamma Hankel kernel")

# Finite-depth certificate for the mixed seam law.  f_j represents
# F(t-u-j a); shifting u from 0 to a sends f_j to f_(j+1).
J = 6
zeta, rho = sp.symbols("zeta rho")
fdepth = sp.symbols(f"f0:{J + 2}")
x_at_zero = sum(rho**j * fdepth[j] * zeta**j for j in range(J + 1))
x_at_a = sum(rho**j * fdepth[j + 1] * zeta**j for j in range(J))
seam_residual = sp.expand(x_at_zero - rho * zeta * x_at_a)
assert seam_residual == fdepth[0]

# Return length u+j a is generated by u+a z d/dz.
u, a = sp.symbols("u a")
length_action = sp.expand(u * x_at_zero + a * zeta * sp.diff(x_at_zero, zeta))
length_expected = sum(
    (u + j * a) * rho**j * fdepth[j] * zeta**j for j in range(J + 1)
)
assert sp.simplify(length_action - length_expected) == 0

print("PASS: mixed seam law on every retained depth")
print("PASS: canonical return-length generator")

# Universal-half-line chart: ell=u+j*a turns multiplication by ell into
# u+a*z*d/dz in every prime cell coordinate.
ell_chart = sum(
    (u + j * a) * rho**j * fdepth[j] * zeta**j for j in range(J + 1)
)
assert sp.simplify(length_action - ell_chart) == 0

# Exact weighted ANOVA for the seam traces.  The e_i stand for arbitrary
# scalar components of E_{p,T}h; polarization gives the Hilbert-space form.
w1, w2, w3 = sp.symbols("w1 w2 w3", positive=True, real=True)
e1, e2, e3 = sp.symbols("e1 e2 e3", real=True)
weights = [w1, w2, w3]
samples = [e1, e2, e3]
mean = sum(w * e for w, e in zip(weights, samples))
anova = sum(w * e**2 for w, e in zip(weights, samples)) - mean**2
centered = sum(w * (e - mean) ** 2 for w, e in zip(weights, samples))
assert sp.simplify((anova - centered).subs(w3, 1 - w1 - w2)) == 0
pairwise = sp.Rational(1, 2) * sum(
    weights[i] * weights[j] * (samples[i] - samples[j]) ** 2
    for i in range(3)
    for j in range(3)
)
assert sp.simplify((centered - pairwise).subs(w3, 1 - w1 - w2)) == 0

print("PASS: every prime length chart is the universal return length")
print("PASS: exact weighted seam-trace ANOVA")
print("PASS: pairwise relative-prime square for seam leakage")

# Exact Euler transgression.  It suffices to check one exponential Laplace
# mode; linearity and Laplace uniqueness give the compact C^1 identity.
s, a_pos = sp.symbols("s a_pos", positive=True, real=True)
ell = sp.symbols("ell", real=True)
q_a = sp.exp(-s * a_pos)
one_cell = sp.integrate(
    (ell / a_pos - sp.Rational(1, 2)) * (-s) * sp.exp(-s * ell),
    (ell, 0, a_pos),
)
euler_rhs = 1 / (a_pos * s) + sp.Rational(1, 2) + one_cell / (1 - q_a)
assert sp.simplify(euler_rhs - 1 / (1 - q_a)) == 0

print("PASS: exact Euler transgression of a lattice trace")

# The same transgression is the symmetric imaginary-axis sampling of the
# depth resolvent.  The classical paired partial-fraction sum is coth.
c = sp.symbols("c", positive=True, real=True)
imaginary_axis_sum = sp.Rational(1, 2) * sp.coth(a_pos * c / 2) - 1 / (a_pos * c)
euler_transgression = (
    1 / (1 - sp.exp(-a_pos * c))
    - 1 / (a_pos * c)
    - sp.Rational(1, 2)
)
quadrant_bridge = (imaginary_axis_sum - euler_transgression).rewrite(sp.exp)
assert sp.simplify(sp.together(quadrant_bridge)) == 0

print("PASS: real-axis Gamma and imaginary-axis seam resolvent bridge")

# Weighted Bergman Green current: A_zeta has eigenvalue 2 alpha_n while
# the metric has coefficient 1/alpha_n, leaving exactly twice Hardy mass.
n = sp.symbols("n", integer=True, nonnegative=True)
alpha_n = n + sp.Rational(1, 4)
lambda_n = 2 * n + sp.Rational(1, 2)
assert sp.simplify(lambda_n / alpha_n - 2) == 0

print("PASS: coefficient-one radial Bergman-to-Hardy Green current")
